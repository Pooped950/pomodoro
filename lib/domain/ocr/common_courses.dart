/// 全部常见课程名（各学科合并）
///
/// 用 `Set` 去重；调用方（`correctByCourseVocab`）会按**长度分桶**加速，
/// 所以这里不需要预先排序。
final Set<String> kCommonCourseNames = <String>{
  ...kCommonCoursesPolitics,
  ...kCommonCoursesLiberalArts,
  ...kCommonCoursesScience,
  ...kCommonCoursesEngineering,
};

/// 词表里**出现过的所有汉字** —— 用来判断"这个差异字像不像 OCR 认错的"。
///
/// 见 [correctByCourseVocab] 里那条关键判据。
final Set<String> kCommonCourseChars = <String>{
  for (final String c in kCommonCourseNames) ...c.split(''),
};

/// 用常见课程词表**纠正 OCR 认错的课名**。
///
/// ## 用户报的问题（2026-10-09）
///
/// `毛泽东思想和中国特色社会主义理论体系概论` 被认成 **`毛淨东…`** ——
/// 伟人名字认错，必须纠。这类"整块认错字"靠投票修不了（所有格子都认错）。
///
/// ## ⚠️ 最难的一步：区分「OCR 认错」和「本来就是另一门课」
///
/// 光看"差几个字"是不够的：
///
///   - `毛淨东…概论` vs `毛泽东…概论` —— 差 1 字，**是 OCR 认错**，要纠
///   - `美国文学史及作品选读` vs `英国文学史及作品选读` —— 也差 1 字，
///     但**是两门真实存在的不同课**，纠了就是灾难
///
/// 判据：**差异字里至少有一个是"词表里从没出现过的字"**（= 生僻/不可能
/// 出现在课程名里的字）才算认错。
///
///   - `淨` 在词表的所有字里**找不到** → 可疑 → 纠 ✓
///   - `美` / `英` 在词表里**都出现过** → 合法差异 → 不纠 ✓
///
/// 这样既治得了 `毛淨东`，又不会把英美文学搞混。
///
/// ## 其它限制
///
///   - **长度必须完全相同**（OCR 认错字不会改变字符数）
///   - 差异字数上限：短课名 1 个，长课名（≥8 字）2 个
///   - 词表命中就原样返回，不做无谓的改写
String correctByCourseVocab(String raw, {Set<String>? vocab}) {
  final String s = raw.trim();
  if (s.length < 3) return raw;

  final Set<String> pool = vocab ?? kCommonCourseNames;
  if (pool.contains(s)) return raw;

  final Set<String> chars = identical(pool, kCommonCourseNames)
      ? kCommonCourseChars
      : <String>{for (final String c in pool) ...c.split('')};

  // ⚠️ **前置闸门**：输入里必须含有"课程名里不可能出现的字"，才可能是 OCR 认错。
  //
  // 这一步是整个函数的灵魂 —— 它把「OCR 认错」和「本来就是另一门课」分开：
  //   - `毛淨东…` 里的 `淨`、`社杜会` 里的 `杜`、`体休` 里的 `休`
  //     → 词表的所有字里都找不到 → 可疑 → 放行去比对
  //   - `美国文学史及作品选读` 里的 `美`、`英`
  //     → 词表里都出现过（`英美文学`）→ **不可疑** → 直接返回，绝不误纠
  //
  // 没有这道闸门的话，`美国文学史…` 和 `英国文学史…` 只差 1 字就会被互相
  // 纠来纠去 —— 那才是真正的灾难。
  if (!s.split('').any((String c) => !chars.contains(c))) return raw;

  // 长度 ≤6 只容忍 1 字之差；更长的课名容忍 2 字
  final int limit = s.length <= 6 ? 1 : 2;

  String? best;
  int bestCost = limit + 1;
  for (final String cand in pool) {
    if ((cand.length - s.length).abs() > limit) continue;
    final int cost = _levenshtein(s, cand, limit);
    if (cost > 0 && cost <= limit && cost < bestCost) {
      bestCost = cost;
      best = cand;
    }
  }
  return best ?? raw;
}

/// 编辑距离（Levenshtein），超过 [limit] 就提前收敛返回 `limit + 1`。
///
/// 用编辑距离而不是逐位比较，是因为 ML Kit 的错法**不止"替换"一种**：
/// 实测同一门课里既有 `社`→`社杜`（**多认**一个字），又有 `系`→`休`
/// （**认错**一个字）—— 混合起来逐位比较完全对不上。
int _levenshtein(String a, String b, int limit) {
  final int n = a.length;
  final int m = b.length;
  if ((n - m).abs() > limit) return limit + 1;

  List<int> prev = List<int>.generate(m + 1, (int i) => i);
  List<int> cur = List<int>.filled(m + 1, 0);

  for (int i = 1; i <= n; i++) {
    cur[0] = i;
    int rowMin = cur[0];
    for (int j = 1; j <= m; j++) {
      final int sub = prev[j - 1] + (a[i - 1] == b[j - 1] ? 0 : 1);
      final int del = prev[j] + 1;
      final int ins = cur[j - 1] + 1;
      int v = sub < del ? sub : del;
      if (ins < v) v = ins;
      cur[j] = v;
      if (v < rowMin) rowMin = v;
    }
    // 整行最小值都超过上限 → 后面只会更大，提前退出
    if (rowMin > limit) return limit + 1;
    final List<int> tmp = prev;
    prev = cur;
    cur = tmp;
  }
  return prev[m];
}

